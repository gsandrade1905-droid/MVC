    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         String nome = jTextField1.getText().trim();
    String email = jTextField2.getText().trim();
    String senha = jTextField3.getText();

    // Verificar se os campos estão preenchidos
    if (nome.isEmpty() || email.isEmpty() || senha.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Preencha todos os campos!"
        );
        return;
    }

    // Comando SQL para cadastrar o usuário
    String sql = "INSERT INTO usuarios (nome, email, senha) VALUES (?, ?, ?)";

    try (
        Connection con = conexao.conectar();
        PreparedStatement stmt = con.prepareStatement(sql)
    ) {
        stmt.setString(1, nome);
        stmt.setString(2, email);
        stmt.setString(3, senha);

        // Executar o cadastro
        stmt.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(
            this, "Usuário cadastrado com sucesso!"
        );

        // Limpar os campos depois do cadastro
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");

    } catch (SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Erro ao cadastrar usuário: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String email = jTextField2.getText().trim();

    if (email.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Digite o e-mail do usuário que deseja apagar!"
        );
        return;
    }

    int confirmacao = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Deseja realmente apagar o usuário com e-mail " + email + "?",
        "Confirmar exclusão",
        javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirmacao != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    String sql = "DELETE FROM usuarios WHERE email = ?";

    try (
        Connection con = conexao.conectar();
        PreparedStatement stmt = con.prepareStatement(sql)
    ) {
        stmt.setString(1, email);

        int linhasAfetadas = stmt.executeUpdate();

        if (linhasAfetadas > 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Usuário apagado com sucesso!"
            );

            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");

        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Nenhum usuário encontrado com esse e-mail."
            );
        }

    } catch (SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Erro ao apagar usuário: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_jButton2ActionPerformed

